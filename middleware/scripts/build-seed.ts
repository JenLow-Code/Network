/**
 * Generates database/seeds/demo_seed.sql from scripts/demo-data.ts.
 *   npm run seed:sql
 * The SQL is idempotent: run it any number of times (local, preview or remote) without
 * duplicating rows. It never touches non-demo records.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BIBLE, DREAMS, ENCOURAGEMENTS, LINEAGE, MUSIC, PHOTO, SAME_DREAM, SHOWCASES, USERS, type PhotoKey } from './demo-data.ts';

const q = (v: string | number | null | undefined) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : "'" + v.replace(/'/g, "''") + "'");
/** The remote rows were written with ASCII apostrophes; immutable titles must match exactly. */
const exact = (s: string) => s.replace(/’/g, "'");
const uid = (n: string) => `demo-user-${n}`;
const did = (id: string) => `demo-dream-${id}`;
const pub = (id: string) => `demo-pub-dream-${id}`;
const photoUrl = (k: PhotoKey) => `https://images.unsplash.com/photo-${PHOTO[k]}?w=900&q=82`;
const ATTRIBUTION = 'Photo Unsplash — illustration de démonstration, ne représente pas un membre';
const lines: string[] = [];
const out = (s: string) => lines.push(s);

out('-- JenLow Network · demo dataset (fictional). GENERATED by middleware/scripts/build-seed.ts — edit demo-data.ts, then `npm run seed:sql`.');
out('-- Idempotent. Touches only demo-* identifiers. Demo profiles stay deactivated (they can never sign in).');
out('-- Requires migrations 0001–0011.');

// Users ---------------------------------------------------------------------------------
for (const u of USERS) {
  out(`INSERT OR IGNORE INTO users(id,handle,display_name,email,account_status,is_demo) VALUES(${q(uid(u.n))},${q('mock' + u.n)},${q(u.name)},${q(`demo-user-${u.n}@example.invalid`)},'deactivated',1);`);
  out(`UPDATE users SET display_name=${q(u.name)},bio=${q(u.bio)},city=${q(u.city)},country_code=${q(u.country)},is_demo=1,account_status='deactivated',updated_at=CURRENT_TIMESTAMP WHERE id=${q(uid(u.n))};`);
  out(`INSERT OR IGNORE INTO user_preferences(user_id,discoverable) VALUES(${q(uid(u.n))},0);`);
  for (const [talent, level, f = {}] of u.talents) {
    out(`INSERT OR IGNORE INTO user_talents(user_id,talent_id,level,can_teach,wants_to_learn,wants_tandem,available_for_projects,description,visibility) VALUES(${q(uid(u.n))},${q(talent)},${level},${f.teach ? 1 : 0},${f.learn ? 1 : 0},${f.tandem ? 1 : 0},${f.available ? 1 : 0},${q(f.description ?? null)},'public');`);
  }
}

// Media (attributed external images) ------------------------------------------------------
const mediaId = (owner: string, k: PhotoKey) => `demo-media-${owner}-${k}`;
const media = new Set<string>();
const needMedia = (owner: string, k: PhotoKey) => {
  const id = mediaId(owner, k);
  if (!media.has(id)) {
    media.add(id);
    out(`INSERT OR IGNORE INTO media_assets(id,owner_id,external_url,media_type,mime_type,storage_status,purpose,attribution,source_name) VALUES(${q(id)},${q(uid(owner))},${q(photoUrl(k))},'image','image/jpeg','ready','dream_cover',${q(ATTRIBUTION)},'Unsplash');`);
  }
  return id;
};

// Dreams ---------------------------------------------------------------------------------
const testimonyDefault = 'Un premier résultat a été réalisé et partagé avec le collectif.';
DREAMS.forEach((d, i) => {
  const cover = needMedia(d.owner, d.cover);
  const started = d.phase === 'dream' ? 'NULL' : 'CURRENT_TIMESTAMP';
  const growing = d.phase === 'growth' || d.phase === 'testimony' ? 'CURRENT_TIMESTAMP' : 'NULL';
  const completed = d.phase === 'testimony' ? 'CURRENT_TIMESTAMP' : 'NULL';
  // Same column values as the existing remote rows; richer content is added below in mutable fields.
  out(`INSERT OR IGNORE INTO dreams(id,title,summary,phase,visibility,created_by,started_at,growing_at,completed_at,testimony_text) VALUES(${q(did(d.id))},${q(exact(d.title))},${q(exact(d.summary))},${q(d.phase)},'public',${q(uid(d.owner))},${started},${growing},${completed},${d.phase === 'testimony' ? q(d.testimony ?? testimonyDefault) : 'NULL'});`);
  out(`INSERT OR IGNORE INTO dream_owners(dream_id,user_id,status,accepted_at) VALUES(${q(did(d.id))},${q(uid(d.owner))},'accepted',CURRENT_TIMESTAMP);`);
  // Cover may be set once on legacy Floraisons (trigger allows first assignment only).
  out(`UPDATE dreams SET cover_media_id=${q(cover)},category=${q(d.category)} WHERE id=${q(did(d.id))} AND cover_media_id IS NULL;`);
  if (d.phase !== 'testimony') {
    out(`UPDATE dreams SET motivation=coalesce(motivation,${q(d.motivation ?? null)}),goal_date=coalesce(goal_date,${q(d.goal ?? null)}) WHERE id=${q(did(d.id))};`);
  } else {
    out(`UPDATE dreams SET testimony_primary_asset_id=${q(cover)} WHERE id=${q(did(d.id))} AND testimony_primary_asset_id IS NULL;`);
  }
  const hoursAgo = i * 3 + (d.phase === 'testimony' ? 1 : 0);
  out(`INSERT OR IGNORE INTO publications(id,type,author_id,dream_id,title,cover_asset_id,visibility,created_at,updated_at) VALUES(${q(pub(d.id))},'dream',${q(uid(d.owner))},${q(did(d.id))},${q(exact(d.title))},${q(cover)},'public',datetime('2026-11-01 18:00:00','-${hoursAgo} hours'),datetime('2026-11-01 18:00:00','-${hoursAgo} hours'));`);
  for (const [j, k] of (d.gallery ?? []).entries()) {
    out(`INSERT OR IGNORE INTO dream_media(dream_id,media_id,role,sort_order,added_by) VALUES(${q(did(d.id))},${q(needMedia(d.owner, k))},'gallery',${j},${q(uid(d.owner))});`);
  }
  (d.needs ?? []).forEach((n, j) => {
    const needId = `demo-need-${d.id}-${j + 1}`;
    out(`INSERT OR IGNORE INTO dream_needs(id,dream_id,talent_id,label,slots_total,category,required_level,description,is_required,amount_cents,currency,sort_order,updated_at) VALUES(${q(needId)},${q(did(d.id))},${q(n.talent ?? null)},${q(n.label)},${n.slots ?? 1},${q(n.category ?? 'person')},${n.level ?? 'NULL'},${q(n.description ?? null)},${n.required === false ? 0 : 1},${n.amountCents ?? 'NULL'},${n.amountCents ? "'EUR'" : 'NULL'},${j},CURRENT_TIMESTAMP);`);
    for (const helper of n.filledBy ?? []) {
      const offerId = `demo-offer-${d.id}-${j + 1}-${helper}`;
      out(`INSERT OR IGNORE INTO dream_help_offers(id,need_id,dream_id,offered_by,message,status,talent_id) VALUES(${q(offerId)},${q(needId)},${q(did(d.id))},${q(uid(helper))},'Je serais heureux·se d’aider.','pending',${q(n.talent ?? null)});`);
      // Acceptance goes through the same trigger as the API: it fills exactly one slot, once.
      out(`UPDATE dream_help_offers SET status='accepted',responded_at=CURRENT_TIMESTAMP,responded_by=${q(uid(d.owner))} WHERE id=${q(offerId)} AND status='pending';`);
      out(`INSERT OR IGNORE INTO dream_collaborators(dream_id,user_id,status,role_title,invited_by,accepted_at) VALUES(${q(did(d.id))},${q(uid(helper))},'accepted',${q(n.label)},${q(uid(d.owner))},CURRENT_TIMESTAMP);`);
    }
    for (const helper of n.pendingFrom ?? []) {
      out(`INSERT OR IGNORE INTO dream_help_offers(id,need_id,dream_id,offered_by,message,status,talent_id) VALUES(${q(`demo-offer-${d.id}-${j + 1}-${helper}`)},${q(needId)},${q(did(d.id))},${q(uid(helper))},'Disponible à partir du mois prochain.','pending',${q(n.talent ?? null)});`);
    }
    if (n.manual) {
      out(`UPDATE dream_needs SET manual_confirmed=1,slots_filled=slots_filled+1 WHERE id=${q(needId)} AND manual_confirmed=0;`);
    }
  });
  (d.journal ?? []).forEach(([date, body], j) => {
    out(`INSERT OR IGNORE INTO dream_entries(id,dream_id,author_id,entry_type,body,entry_date,visibility) VALUES(${q(`demo-entry-${d.id}-${j + 1}`)},${q(did(d.id))},${q(uid(d.owner))},'progress_comment',${q(body)},${q(date)},'public');`);
  });
  if (d.phase === 'testimony' && d.testimony) {
    out(`INSERT OR IGNORE INTO dream_entries(id,dream_id,author_id,entry_type,body,visibility) VALUES(${q(`demo-entry-${d.id}-testimony`)},${q(did(d.id))},${q(uid(d.owner))},'testimony',${q(d.testimony)},'public');`);
  }
  out(`INSERT OR IGNORE INTO dream_phase_history(id,dream_id,from_phase,to_phase,changed_by,reason) VALUES(${q(`demo-history-${d.id}`)},${q(did(d.id))},NULL,${q(d.phase)},${q(uid(d.owner))},'demo seed');`);
});

for (const [dream, user] of SAME_DREAM) out(`INSERT OR IGNORE INTO dream_same_dream(dream_id,user_id) VALUES(${q(did(dream))},${q(uid(user))});`);
for (const [dream, user] of ENCOURAGEMENTS) out(`INSERT OR IGNORE INTO dream_encouragements(dream_id,user_id) VALUES(${q(did(dream))},${q(uid(user))});`);
for (const [from, to] of LINEAGE) {
  out(`INSERT OR IGNORE INTO dream_lineage(originating_dream_id,inspired_dream_id) VALUES(${q(did(from))},${q(did(to))});`);
  out(`INSERT OR IGNORE INTO dream_inspirations(dream_id,publication_id,added_by) VALUES(${q(did(to))},${q(pub(from))},${q(uid(DREAMS.find(d => d.id === to)!.owner))});`);
}

// Talent showcases --------------------------------------------------------------------------
SHOWCASES.forEach(([owner, talent, art], i) => {
  out(`UPDATE user_talents SET illustration=${q(art)} WHERE user_id=${q(uid(owner))} AND talent_id=${q(talent)};`);
  out(`INSERT OR IGNORE INTO talent_posts(id,user_id,talent_id,visibility,created_at,updated_at) VALUES(${q(`demo-talent-${owner}-${talent.replace('talent-', '')}`)},${q(uid(owner))},${q(talent)},'public',datetime('2026-11-01 18:00:00','-${i * 11 + 2} hours'),datetime('2026-11-01 18:00:00','-${i * 11 + 2} hours'));`);
});

// Bible posts (Psalm 150, Louis Segond 1910) --------------------------------------------------
BIBLE.forEach((b, i) => {
  const id = `demo-pub-bible-${b.id}`;
  const img = needMedia(b.owner, b.photo);
  out(`INSERT OR IGNORE INTO publications(id,type,author_id,title,cover_asset_id,visibility,created_at,updated_at) VALUES(${q(id)},'bible',${q(uid(b.owner))},${q('Psaumes 150:' + b.verse)},${q(img)},'public',datetime('2026-11-01 18:00:00','-${i * 17 + 5} hours'),datetime('2026-11-01 18:00:00','-${i * 17 + 5} hours'));`);
  out(`INSERT OR IGNORE INTO bible_posts(publication_id,edition_id,book_id,chapter,start_verse,end_verse,custom_image_asset_id,caption) VALUES(${q(id)},'edition-lsg1910','book-PSA',150,${b.verse},${b.verse},${q(img)},${q(b.caption)});`);
});

// Music (first-party demo audio bundled in the app: app-asset:<name>) --------------------------
MUSIC.forEach((m, i) => {
  const pubId = `demo-pub-music-${m.id}`, trackId = `demo-track-${m.id}`, rightsId = `demo-rights-${m.id}`, audioId = `demo-audio-${m.id}`;
  const cover = needMedia(m.owner, m.photo);
  out(`INSERT OR IGNORE INTO media_assets(id,owner_id,external_url,media_type,mime_type,duration_ms,storage_status,purpose,attribution,source_name) VALUES(${q(audioId)},${q(uid(m.owner))},${q('app-asset:' + m.asset)},'audio','audio/wav',8200,'ready','music_audio','Extrait audio de démonstration fourni par JenLow pour la bêta','JenLow');`);
  out(`INSERT OR IGNORE INTO music_rights(id,publisher_id,original_creator_name,rights_holder_name,license_type,attribution_text,adaptations_allowed,reviewed_status) VALUES(${q(rightsId)},${q(uid(m.owner))},'JenLow (démo)','JenLow','own_work','Extrait audio de démonstration fourni par JenLow pour la bêta',1,'approved');`);
  out(`INSERT OR IGNORE INTO publications(id,type,author_id,title,cover_asset_id,visibility,created_at,updated_at) VALUES(${q(pubId)},'music',${q(uid(m.owner))},${q(m.title)},${q(cover)},'public',datetime('2026-11-01 18:00:00','-${i * 13 + 4} hours'),datetime('2026-11-01 18:00:00','-${i * 13 + 4} hours'));`);
  out(`INSERT OR IGNORE INTO music_tracks(id,publication_id,publisher_id,audio_asset_id,cover_asset_id,rights_id,duration_ms,description,song_author) VALUES(${q(trackId)},${q(pubId)},${q(uid(m.owner))},${q(audioId)},${q(cover)},${q(rightsId)},8200,${q(m.description)},'Démo JenLow');`);
  out(`INSERT OR IGNORE INTO music_contributors(track_id,credit_order,user_id,display_name,contribution) VALUES(${q(trackId)},0,NULL,'JenLow (démo)','Audio de démonstration');`);
});

const target = join(import.meta.dirname, '..', '..', 'database', 'seeds', 'demo_seed.sql');
writeFileSync(target, lines.join('\n') + '\n');
console.log(`wrote ${lines.length} statements to ${target}`);
